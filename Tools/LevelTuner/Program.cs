// Level tuner: plays every level in LevelCatalog many times with a casual-player bot (goal-focused,
// but about a third of its moves are random) and picks each level's move count so the bot wins about
// TargetWinRate of the games. Star thresholds come from the same games. Writes LevelTuning.cs.
//
// Run from this folder after changing LevelCatalog:
//   dotnet run -c Release -- ../../Assets/_Project/Scripts/Editor/LevelTuning.cs 500
// then in Unity: Flowers -> Rebuild Levels.

using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using Flowers.Board;
using Flowers.Editor;
using Flowers.Levels;

int games = args.Length > 1 ? int.Parse(args[1]) : 200;
const int Cap = 90;
var results = new (LevelSpec spec, int moves, int two, int three, double win, double median, string err)[LevelCatalog.All.Length];
var sw = Stopwatch.StartNew();

Parallel.For(0, LevelCatalog.All.Length, li =>
{
    var spec = LevelCatalog.All[li];
    try
    {
        var layout = BoardLayout.Parse(spec.Layout);
        var def = new LevelDefinition(layout, spec.Types, Cap, spec.Goals, 1, 1);
        string problem = def.Validate();
        if (problem != null) { results[li] = (spec, 0, 0, 0, 0, 0, problem); return; }

        var needed = new List<int>();
        for (int g = 0; g < games; g++) needed.Add(PlayGame(def, 1000 + g));
        needed.Sort();

        int m = Cap;
        for (int cand = 3; cand <= Cap; cand++)
            if (needed.Count(n => n <= cand) >= spec.TargetWinRate * games) { m = cand; break; }

        var wins = needed.Where(n => n <= m).ToList();
        int Q(double q) => wins[Math.Min(wins.Count - 1, (int)(q * wins.Count))];
        int three = m - Q(0.40), two = m - Q(0.75);
        two = Math.Max(1, two); three = Math.Max(two, three); three = Math.Min(three, m - 1); two = Math.Min(two, three);
        results[li] = (spec, m, two, three, needed.Count(n => n <= m) / (double)games, needed[games / 2], null);
    }
    catch (Exception e) { results[li] = (spec, 0, 0, 0, 0, 0, e.GetType().Name + ": " + e.Message); }
});

Console.WriteLine($"{"Level",-8} {"Moves",5} {"2*",3} {"3*",3} {"Win",6} {"Median",6} Target  ({sw.Elapsed.TotalSeconds:F0}s, {games} games each)");
foreach (var r in results)
    Console.WriteLine(r.err != null ? $"{r.spec.Name,-8} ERROR {r.err}"
        : $"{r.spec.Name,-8} {r.moves,5} {r.two,3} {r.three,3} {r.win,6:P0} {r.median,6} {r.spec.TargetWinRate:P0}");

// Write the tuning file used by Unity.
var sb = new StringBuilder();
sb.AppendLine("// <auto-generated> Written by the level tuner (simulated games with a goal-focused bot). Do not edit by hand;");
sb.AppendLine("// change LevelCatalog (layout, goals, TargetWinRate) and re-run the tuner instead. </auto-generated>");
sb.AppendLine("using System.Collections.Generic;");
sb.AppendLine();
sb.AppendLine("namespace Flowers.Editor");
sb.AppendLine("{");
sb.AppendLine("    public static class LevelTuning");
sb.AppendLine("    {");
sb.AppendLine($"        /// <summary>Level name → (moves, 2-star moves left, 3-star moves left). {games} simulated games per level.</summary>");
sb.AppendLine("        public static readonly Dictionary<string, (int moves, int twoStar, int threeStar)> Values = new Dictionary<string, (int, int, int)>");
sb.AppendLine("        {");
foreach (var r in results)
    if (r.err == null)
        sb.AppendLine($"            {{ \"{r.spec.Name}\", ({r.moves}, {r.two}, {r.three}) }}, // bot win rate {r.win:P0} (target {r.spec.TargetWinRate:P0}), median {r.median} moves");
sb.AppendLine("        };");
sb.AppendLine("    }");
sb.AppendLine("}");
if (args.Length > 0 && args[0].Length > 0) File.WriteAllText(args[0], sb.ToString());

static int PlayGame(LevelDefinition def, int seed)
{
    var rng = new Random(seed);
    var engine = new BoardEngine(def.Layout, def.TypeCount, new Random(seed * 7 + 1));
    var session = new LevelSession(def);
    int used = 0;
    while (session.State == LevelState.Playing)
    {
        var moves = MoveFinder.FindAllValidMoves(engine.Grid);
        if (moves.Count == 0) return int.MaxValue;
        Move best = moves[0]; double bestValue = double.MinValue;
        // A casual player: about a third of the time just plays any move that matches.
        bool casual = rng.NextDouble() < 0.35;
        if (casual) best = moves[rng.Next(moves.Count)];
        else foreach (var m in moves)
        {
            var sim = new BoardEngine(engine.Grid.Clone(), new Random(rng.Next()));
            var r = sim.TrySwap(m.A, m.B);
            double v = Value(session, r) + rng.NextDouble() * 0.01;
            if (v > bestValue) { bestValue = v; best = m; }
        }
        session.ApplySwap(engine.TrySwap(best.A, best.B));
        used++;
        if (used >= def.Moves) break;
    }
    return session.State == LevelState.Won ? used : int.MaxValue;
}

static double Value(LevelSession session, SwapResult r)
{
    var c = new Dictionary<GoalKind, double>();
    var collect = new int[6];
    double points = 0, total = 0;
    for (int i = 0; i < r.Steps.Count; i++)
    {
        var s = r.Steps[i];
        foreach (var f in s.Cleared) collect[f.Type]++;
        total += s.Cleared.Count;
        points += (s.Cleared.Count * 10 + (s.PotHits.Count + s.VinesFreed.Count + s.SoilCleared.Count) * 20) * (i + 1);
        Add(c, GoalKind.BreakPots, s.PotHits.Count * 0.6 + s.PotHits.Count(h => h.LayersLeft == 0) * 0.4);
        Add(c, GoalKind.FreeVines, s.VinesFreed.Count);
        Add(c, GoalKind.ClearSoil, s.SoilCleared.Count);
    }
    double value = total * 0.05;
    foreach (var g in session.Goals)
    {
        if (g.IsComplete) continue;
        double contribution = g.Goal.Kind switch
        {
            GoalKind.CollectFlower => collect[g.Goal.FlowerType],
            GoalKind.Score => points / 40.0,
            _ => c.TryGetValue(g.Goal.Kind, out var x) ? x : 0,
        };
        value += Math.Min(contribution, g.Remaining) * (g.Goal.Kind == GoalKind.Score ? 1 : 1.5);
    }
    return value;
}

static void Add(Dictionary<GoalKind, double> d, GoalKind k, double v) => d[k] = (d.TryGetValue(k, out var x) ? x : 0) + v;
